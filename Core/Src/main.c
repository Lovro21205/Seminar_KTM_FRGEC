/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  HAL_Init();
  SystemClock_Config();
  MX_GPIO_Init(); // Koristi postojeću funkciju iz main.h

  SSD1306_Init(); // Inicijalizacija OLED displaya
  HX711_Init();   // Inicijalizacija senzora težine

  // Prikaži početnih 0g
  SSD1306_Clear();
  SSD1306_DrawSmallG(40, 28);
  SSD1306_DrawBigDigit(50, 20, 0);
  SSD1306_UpdateScreen();
  HAL_Delay(2000);

  /* Infinite loop */
  while (1)
  {
    float weight = HX711_GetWeight(); // Očitaj težinu

    SSD1306_Clear();

    // Formatiraj broj
    char buffer[16];
    if (weight < 0)
        sprintf(buffer, "0");
    else
        sprintf(buffer, "%d", (int)weight);

    int len = strlen(buffer);

    // Crtanje 'g' (desno od broja)
    SSD1306_DrawSmallG(40, 28);

    // Crtanje broja
    int number_x = 50;
    for (int i = 0; i < len; i++)
    {
        SSD1306_DrawBigDigit(number_x + i * 9, 20, buffer[i] - '0');
    }

    SSD1306_UpdateScreen();
    HAL_Delay(100); // Osvježi 10 puta u sekundi
  }
}

/**
  * @brief System Clock Configuration
  * @retval None
  */
void SystemClock_Config(void)
{
  RCC_OscInitTypeDef RCC_OscInitStruct = {0};
  RCC_ClkInitTypeDef RCC_ClkInitStruct = {0};

  RCC_OscInitStruct.OscillatorType = RCC_OSCILLATORTYPE_HSI;
  RCC_OscInitStruct.HSIState = RCC_HSI_ON;
  RCC_OscInitStruct.HSICalibrationValue = RCC_HSICALIBRATION_DEFAULT;
  RCC_OscInitStruct.PLL.PLLState = RCC_PLL_ON;
  RCC_OscInitStruct.PLL.PLLSource = RCC_PLLSOURCE_HSI;
  RCC_OscInitStruct.PLL.PLLMUL = RCC_PLLMUL_12;
  RCC_OscInitStruct.PLL.PREDIV = RCC_PREDIV_DIV1;
  if (HAL_RCC_OscConfig(&RCC_OscInitStruct) != HAL_OK)
  {
    Error_Handler();
  }

  RCC_ClkInitStruct.ClockType = RCC_CLOCKTYPE_HCLK|RCC_CLOCKTYPE_SYSCLK
                              |RCC_CLOCKTYPE_PCLK1;
  RCC_ClkInitStruct.SYSCLKSource = RCC_SYSCLKSOURCE_PLLCLK;
  RCC_ClkInitStruct.AHBCLKDivider = RCC_SYSCLK_DIV1;
  RCC_ClkInitStruct.APB1CLKDivider = RCC_HCLK_DIV1;

  if (HAL_RCC_ClockConfig(&RCC_ClkInitStruct, FLASH_LATENCY_1) != HAL_OK)
  {
    Error_Handler();
  }
}

